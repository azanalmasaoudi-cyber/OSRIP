"""Write the Visual Studio solution and project files, so Solution Explorer shows every OSRIP file.

    backend\\.venv\\Scripts\\python.exe tools\\make_vs_projects.py

* ``backend\\OSRIP.Backend.pyproj``: the FastAPI code, tests, scripts and migrations, with the
  backend's own ``.venv`` as the Python environment, so imports resolve and Test Explorer
  can run pytest. The maintenance scripts in ``tools\\`` are linked here too, because they
  run with that environment (Pillow).
* ``frontend\\OSRIP.Frontend.njsproj``: the React/TypeScript interface, its tests and image
  sources. Building it runs ``npm run build`` (TypeScript check and Vite production build);
  Clean removes that output.
* ``OSRIP.sln``: the three projects (``OSRIP.Launcher``, F5: start everything, stays the
  startup project and is not generated) and solution folders for the repository files:
  README, settings, ``.vscode``, ``deploy`` and ``docs``.

Files are listed explicitly. Never listed: generated folders (``node_modules``, ``.venv``,
``dist``, ``obj``, caches, test output), secrets (``.env``), other editors' local state
(``.vs``, ``docs\\.vscode``), and folders that are not part of OSRIP (``docs\\Downloads``, the
old ``OSRIP\\`` copy, ``Web.config``). Run this again after adding or removing files; Visual
Studio offers to reload. Standard library only.
"""

from __future__ import annotations

import os
import uuid
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
FRONTEND = ROOT / "frontend"
SKIP_DIRS = {
    "__pycache__", ".venv", ".pytest_cache", ".ruff_cache", ".vs", "node_modules", "dist",
    "test-results", "playwright-report", "osrip_api.egg-info", ".tmp", "obj", "bin",
}  # fmt: skip
LAUNCHER_GUID = "{4F2B7C1E-8D3A-4B6E-9C21-5A7D0E3F9B12}"
BACKEND_GUID = "{6D3E9A41-2B7C-4F58-A1D0-9C4E7B2F3A15}"
FRONTEND_GUID = "{B82F4C17-5E9A-4D63-8C21-0F7A3E6D9B48}"
ITEMS_GUID = "{9B6E1D42-3C7A-4E58-8F11-2D6A0C5B7E90}"
SOLUTION_GUID = "{C3A1F7B2-6E4D-4A09-B8C5-71D2E9F04A36}"
PYTHON_TYPE = "{888888A0-9F3D-457C-B088-3A5042F75D52}"
NODE_TYPE = "{9092AA53-FB77-4645-B42D-1CCCA6BD08BD}"
FOLDER_TYPE = "{2150E333-8FDC-42A3-9474-1A3956D46DE8}"
TOOLS_SCRIPTS = ("build_editorial_images.py", "build_persona_portraits.py", "make_vs_projects.py")
ROOT_ITEMS = (
    "README.md", "start-osrip.cmd", ".editorconfig", ".vsconfig", ".env.example", ".gitignore",
    ".gitattributes", ".dockerignore",
)  # fmt: skip
# Solution folders: repository folder -> (folders never shown inside it, files never shown).
SOLUTION_FOLDERS = {
    ".vscode": (set(), set()),
    "deploy": ({".vs"}, {".env"}),
    "docs": ({".vs", ".vscode", "Downloads"}, set()),
}


def files(base: Path, folder: str, patterns: tuple[str, ...]) -> list[str]:
    """Relative Windows paths of matching files under ``base/folder``, sorted."""
    start = base / folder
    if not start.exists():
        return []
    found = set()
    for pattern in patterns:
        for path in start.rglob(pattern):
            rel = path.relative_to(base)
            if path.is_file() and not SKIP_DIRS.intersection(rel.parts):
                found.add(str(rel).replace("/", "\\"))
    return sorted(found, key=str.lower)


def folders(paths: list[str]) -> list[str]:
    out = set()
    for p in paths:
        parts = p.split("\\")[:-1]
        for i in range(1, len(parts) + 1):
            out.add("\\".join(parts[:i]) + "\\")
    return sorted(out, key=str.lower)


def items(tag: str, paths: list[str]) -> str:
    return "\n".join(f'    <{tag} Include="{escape(p)}" />' for p in paths)


def linked_tools() -> str:
    # Visual Studio adds a folder entry for the links' virtual "tools" folder when it saves the
    # project (and creates an empty backend\tools); writing it here keeps the file unchanged.
    lines = ['    <Folder Include="tools\\" />']
    for name in TOOLS_SCRIPTS:
        if (ROOT / "tools" / name).exists():
            lines.append(
                f'    <Compile Include="..\\tools\\{name}">\n'
                f"      <Link>tools\\{name}</Link>\n"
                "    </Compile>"
            )
    return "\n".join(lines)


