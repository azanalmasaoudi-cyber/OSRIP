def folder_guid(path: str) -> str:
    """Stable id for a solution folder, so regenerating never changes the solution needlessly."""
    return "{" + str(uuid.uuid5(uuid.NAMESPACE_URL, f"osrip.sln/{path}")).upper() + "}"


def solution_folders() -> dict[str, list[str]]:
    """Repository folder -> its files (relative Windows paths), for every shown folder."""
    found: dict[str, list[str]] = {}
    for top, (skip_dirs, skip_files) in SOLUTION_FOLDERS.items():
        if not (ROOT / top).is_dir():
            continue
        for current, dirs, names in os.walk(ROOT / top):
            dirs[:] = sorted((d for d in dirs if d not in skip_dirs | SKIP_DIRS), key=str.lower)
            rel = str(Path(current).relative_to(ROOT))
            found[rel] = [
                f"{rel}\\{n}" for n in sorted(names, key=str.lower) if n not in skip_files
            ]
    return found


def solution() -> str:
    lines = [
        "",
        "Microsoft Visual Studio Solution File, Format Version 12.00",
        "# Visual Studio Version 18",
        "VisualStudioVersion = 18.0.11205.157",
        "MinimumVisualStudioVersion = 10.0.40219.1",
    ]
    projects = (
        ("OSRIP.Launcher", "tools\\OSRIP.Launcher.pyproj", PYTHON_TYPE, LAUNCHER_GUID),
        ("OSRIP.Backend", "backend\\OSRIP.Backend.pyproj", PYTHON_TYPE, BACKEND_GUID),
        ("OSRIP.Frontend", "frontend\\OSRIP.Frontend.njsproj", NODE_TYPE, FRONTEND_GUID),
    )
    for name, path, kind, guid in projects:
        lines += [f'Project("{kind}") = "{name}", "{path}", "{guid}"', "EndProject"]

    def folder(name: str, guid: str, paths: list[str]) -> None:
        lines.append(f'Project("{FOLDER_TYPE}") = "{name}", "{name}", "{guid}"')
        if paths:
            lines.append("\tProjectSection(SolutionItems) = preProject")
            lines.extend(f"\t\t{p} = {p}" for p in paths)
            lines.append("\tEndProjectSection")
        lines.append("EndProject")

    folder("Solution Items", ITEMS_GUID, [p for p in ROOT_ITEMS if (ROOT / p).exists()])
    nested = []
    for path, paths in solution_folders().items():
        folder(Path(path).name, folder_guid(path), paths)
        parent = str(Path(path).parent)
        if parent != ".":
            nested.append(f"\t\t{folder_guid(path)} = {folder_guid(parent)}")

    lines += [
        "Global",
        "\tGlobalSection(SolutionConfigurationPlatforms) = preSolution",
        "\t\tDebug|Any CPU = Debug|Any CPU",
        "\t\tRelease|Any CPU = Release|Any CPU",
        "\tEndGlobalSection",
        "\tGlobalSection(ProjectConfigurationPlatforms) = postSolution",
    ]
    # Every project builds: the Python projects have nothing to compile, the frontend runs
    # "npm run build". F5 builds only the startup project (Visual Studio's default).
    for _, _, _, guid in projects:
        for config in ("Debug", "Release"):
            lines += [
                f"\t\t{guid}.{config}|Any CPU.ActiveCfg = {config}|Any CPU",
                f"\t\t{guid}.{config}|Any CPU.Build.0 = {config}|Any CPU",
            ]
    lines += [
        "\tEndGlobalSection",
        "\tGlobalSection(SolutionProperties) = preSolution",
        "\t\tHideSolutionNode = FALSE",
        "\tEndGlobalSection",
        "\tGlobalSection(NestedProjects) = preSolution",
        *nested,
        "\tEndGlobalSection",
        "\tGlobalSection(ExtensibilityGlobals) = postSolution",
        f"\t\tSolutionGuid = {SOLUTION_GUID}",
        "\tEndGlobalSection",
        "EndGlobal",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    for path, text in (
        (BACKEND / "OSRIP.Backend.pyproj", backend_project()),
        (FRONTEND / "OSRIP.Frontend.njsproj", frontend_project()),
    ):
        path.write_text(text, encoding="utf-8", newline="\r\n")
        count = (
            text.count("<Compile ") + text.count("<TypeScriptCompile ") + text.count("<Content ")
        )
        print(f"wrote {path.relative_to(ROOT)} ({count} files)")
    # Visual Studio's own format: UTF-8 with a byte-order mark, Windows line endings.
    (ROOT / "OSRIP.sln").write_text(solution(), encoding="utf-8-sig", newline="\r\n")
    shown = sum(map(len, solution_folders().values()))
    shown += sum((ROOT / p).exists() for p in ROOT_ITEMS)
    print(f"wrote OSRIP.sln (3 projects; {shown} repository files in solution folders)")


if __name__ == "__main__":
    main()
