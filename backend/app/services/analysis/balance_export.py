def _is_number(cell: Any) -> bool:
    if not isinstance(cell, str) or not cell:
        return False
    try:
        float(cell)
    except ValueError:
        return False
    return True


def _cell(value: Any) -> str:
    if value is None:
        return ""
    text = str(value)
    return text if _is_number(text) else safe_cell(text)


def _unit_label(unit: dict[str, str] | None, lang: str) -> str:
    return "" if not unit else unit[f"label_{lang}"]


def export_csv(doc: dict[str, Any], language: str) -> str:
    lang = "ar" if language == "ar" else "en"
    L = LABELS[lang]  # noqa: N806
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([safe_cell(f"# {doc['title'][lang]}")])
    w.writerow([safe_cell(f"# {L['data_mode']}: {mode_label(doc['data_mode'])}")])
    w.writerow([safe_cell(f"# {L['versions']}: {' | '.join(doc['dataset_versions'])}")])
    w.writerow([safe_cell(f"# {L['method']}: {doc['method'][lang]}")])
    for a in doc["assumptions"]:
        w.writerow([safe_cell(f"# {L['assumptions']}: {a[lang]}")])
    for b in doc["balances"]:
        w.writerow([])
        w.writerow(
            [
                _cell(f"{b['id']} {b['title'][lang]}"),
                _cell(L["status"][b["status"]]),
                _cell(b["status_label"][lang]),
            ]
        )
        w.writerow([_cell(f"{L['reason']}: {b['reason'][lang]}")])
        cols = b["table"]["columns"]
        w.writerow(
            [
                _cell(
                    c["label"][lang]
                    + (f" ({_unit_label(c.get('unit'), lang)})" if c.get("unit") else "")
                )
                for c in cols
            ]
        )
        for row in b["table"]["rows"]:
            w.writerow([_cell(row.get(c["key"])) for c in cols])
    w.writerow([])
    w.writerow([_cell(L["recommendations"])])
    w.writerow(L["rec_header"])
    for r in doc["recommendations"]:
        w.writerow([_cell(x) for x in (
            r["id"], r["problem"][lang], r["evidence"][lang], " ".join(r["evidence_ids"]), r["action"][lang], r["quantity"],
            _unit_label(r["quantity_unit"], lang), r["quantity_note"][lang], r["constraints"][lang], L["horizon"][r["horizon"]],
            r["cost"][lang], r["outcome"][lang], L["priority"][r["priority"]], r["priority_basis"][lang], r["kpi"][lang],
            L["nature"][r["nature"]], L["option"].get(r.get("option") or "", ""),
        )])  # fmt: skip
    end = doc.get("conclusion")
    if end:
        w.writerow([])
        w.writerow([_cell(L["conclusion"])])
        for f in end["main_findings"]:
            w.writerow(
                [_cell(L["findings"]), _cell(f["text"][lang]), _cell(" ".join(f["evidence"]))]
            )
        for x in end["evidence_limitations"]:
            w.writerow([_cell(L["evidence_limits"]), _cell(x[lang])])
        for rid in end["immediate_actions"]:
            w.writerow([_cell(L["immediate"]), _cell(rid)])
        for rid in end["medium_term_options"]:
            w.writerow([_cell(L["medium_term"]), _cell(rid)])
        for n in end["next_study"]:
            w.writerow([_cell(L["next_study"]), _cell(n["question"][lang]), _cell(n["data"][lang])])
    w.writerow([])
    w.writerow([_cell(L["gaps"])])
    w.writerow(L["gap_header"])
    for g in doc["data_gaps"]:
        w.writerow(
            [
                _cell(x)
                for x in (
                    g["id"],
                    g["balance"],
                    g["missing"][lang],
                    g["blocks"][lang],
                    (g.get("where") or {}).get(lang),
                )
            ]
        )
    scenario = doc["scenario"]
    if scenario["status"] == "ok" and scenario["table"]:
        w.writerow([])
        w.writerow([_cell(L["scenario"])])
        for a in scenario["assumptions"]:
            w.writerow([_cell(a[lang])])
        cols = scenario["table"]["columns"]
        w.writerow(
            [
                _cell(
                    c["label"][lang]
                    + (f" ({_unit_label(c.get('unit'), lang)})" if c.get("unit") else "")
                )
                for c in cols
            ]
        )
        for row in scenario["table"]["rows"]:
            w.writerow([_cell(row.get(c["key"])) for c in cols])
    w.writerow([])
    w.writerow([_cell(L["sources"])])
    w.writerow(L["source_header"])
    for s in doc["sources"]:
        w.writerow([_cell(x) for x in (
            s["id"], s["indicator_name"][lang], s["area_name"][lang], s["period_label"], s["period_kind"], s["value"],
            s["value_operator"], _unit_label(s["unit"], lang), s["publisher"], s["title"], s["url"], s["publication"],
            s["accessed"], s["dataset_version"], s["record_ref"], s["data_status"], L["yes"] if s["older_context"] else L["no"],
        )])  # fmt: skip
    return buf.getvalue()


# ------------------------------------------------------------------ the spoken summary


def spoken_summary(doc: dict[str, Any], language: str) -> str:
    """A short explanation for listening: the summary sentences, each balance's status in one
    sentence and the number of recommendations, never the table cells one by one."""
    lang = "ar" if language == "ar" else "en"
    parts = [doc["title"][lang] + "."]
    parts += [
        s[lang] for s in doc["summary"][:-1]
    ]  # the closing decision-support line is shown, not read
    for b in doc["balances"]:
        parts.append(f"{b['title'][lang]}: {b['status_label'][lang]}.")
    count = len(doc["recommendations"])
    gaps = len(doc["data_gaps"])
    parts.append(
        f"عدد التوصيات {count}، وعدد المعلومات الناقصة {gaps}؛ التفاصيل في الجداول المعروضة."
        if lang == "ar"
        else f"{count} recommendations and {gaps} items of missing information; the details are in the tables on screen."
    )
    return " ".join(parts)


