def first_turn(session: Session, conv: AssistantConversation) -> bool:
    """No assistant reply yet in this conversation (the introduction belongs here only)."""
    return (
        session.scalar(
            select(func.count()).where(
                AssistantMessage.conversation_id == conv.id, AssistantMessage.role == "assistant"
            )
        )
        or 0
    ) == 0


def resolve_persona(
    session: Session, code: str | None, *, user_id: uuid.UUID | None = None
) -> str | None:
    """The persona that gives the next reply: the one asked for, else the signed-in person's
    saved choice, else the profile's default. A code the active profile does not have is
    refused. Personas change only the name, introduction, portrait and voice: knowledge, tools,
    permissions, sources, history and the guest allowance are the same for each."""
    from app.models import AppUser

    current = profile.active(session)
    if current is None:
        return None
    codes = {x.code for x in profile.personas(current.profile)}
    if code is None and user_id is not None:
        saved = session.scalar(select(AppUser.assistant_persona).where(AppUser.id == user_id))
        code = saved if saved in codes else None
    if code is not None and code not in codes:
        raise unprocessable("unknown_persona", "This assistant persona does not exist.")
    return profile.persona(current.profile, code).code


def profile_turn(
    session: Session,
    conv: AssistantConversation,
    question: str,
    language: str,
    persona: str | None = None,
) -> Reply | None:
    """A greeting, thanks or a question about the assistant or OSRIP gets the approved reply
    from the active profile, in the chosen persona's words. No model is called and no answer
    is charged (a fixed welcome is not an answer). Returns None for every other message."""
    intent = profile.classify(question)
    current = profile.active(session) if intent else None
    if intent is None or current is None:
        return None
    who = profile.persona(current.profile, persona)
    text = profile.reply(
        current.profile,
        intent,
        language,
        first_turn=first_turn(session, conv),
        availability=availability(),
        greeted=profile.has_salam(question),
        who=who,
    )
    return Reply(
        content=text,
        status="profile",
        outcome="profile",
        structured={"profile": {"version": current.version, "intent": intent}},
        persona=who.code,
    )


