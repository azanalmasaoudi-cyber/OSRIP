def _conversation(
    session: Session, principal: Principal, conversation_id: uuid.UUID
) -> AssistantConversation:
    conv = session.get(AssistantConversation, conversation_id)
    if conv is None or conv.user_id != principal.user_id:
        raise not_found(
            "conversation"
        )  # other users' conversations are indistinguishable from missing ones
    return conv


def grounded_expired(entry: dict[str, Any], now: datetime | None = None) -> bool:
    """A Google Search grounded result older than the permitted storage period (the Gemini
    API terms allow at most two years)."""
    try:
        stored = datetime.fromisoformat(str(entry.get("stored_at")))
    except ValueError:
        return True
    now = now or accounts.now()
    return now - stored > timedelta(days=get_settings().grounded_retention_days)


def _structured_out(structured: dict[str, Any] | None) -> dict[str, Any]:
    out = dict(structured or {})
    if out.get("grounded_context"):
        kept = [g for g in out["grounded_context"] if not grounded_expired(g)]
        out["grounded_context"] = kept
        if not kept:
            out.pop("grounded_context")
    return out


def purge_grounded(session: Session) -> int:
    """Remove expired grounded results from stored replies (the replies themselves stay)."""
    removed = 0
    rows = session.scalars(
        select(AssistantMessage).where(AssistantMessage.structured.has_key("grounded_context"))
    )
    for m in rows:
        entries = list((m.structured or {}).get("grounded_context") or [])
        kept = [g for g in entries if not grounded_expired(g)]
        if len(kept) != len(entries):
            removed += len(entries) - len(kept)
            updated = {k: v for k, v in (m.structured or {}).items() if k != "grounded_context"}
            if kept:
                updated["grounded_context"] = kept
            m.structured = updated
    return removed


def _message_out(m: AssistantMessage) -> dict[str, Any]:
    return {
        "id": m.id,
        "role": m.role,
        "content": m.content,
        "status": m.status,
        "evidence": m.evidence,
        "calculations": m.calculations,
        "citations": m.citations,
        "suggestions": m.suggestions,
        "model": m.model,
        "ai_generated": m.role == "assistant" and m.model is not None,
        "created_at": m.created_at.isoformat(),
        "mode": m.mode,
        "structured": _structured_out(m.structured),
        "persona": m.persona,
    }


def list_conversations(session: Session, principal: Principal) -> list[dict[str, Any]]:
    rows = session.scalars(
        select(AssistantConversation)
        .where(AssistantConversation.user_id == principal.user_id)
        .order_by(AssistantConversation.updated_at.desc())
        .limit(50)
    )
    return [
        {
            "id": str(c.id),
            "title": c.title,
            "language": c.language,
            "data_mode": c.data_mode.value,
            "updated_at": c.updated_at.isoformat(),
        }
        for c in rows
    ]


def get_conversation(
    session: Session, principal: Principal, conversation_id: uuid.UUID
) -> dict[str, Any]:
    conv = _conversation(session, principal, conversation_id)
    messages = session.scalars(
        select(AssistantMessage)
        .where(AssistantMessage.conversation_id == conv.id)
        .order_by(AssistantMessage.id)
    )
    return {
        "id": str(conv.id),
        "title": conv.title,
        "language": conv.language,
        "data_mode": conv.data_mode.value,
        "messages": [_message_out(m) for m in messages],
    }


def create_conversation(
    session: Session, principal: Principal, language: str, data_mode: DataMode
) -> dict[str, Any]:
    conv = AssistantConversation(
        user_id=principal.user_id,
        title="New conversation" if language == "en" else "محادثة جديدة",
        language=language,
        data_mode=data_mode,
    )
    session.add(conv)
    session.flush()
    return get_conversation(session, principal, conv.id)


def delete_conversation(session: Session, principal: Principal, conversation_id: uuid.UUID) -> None:
    conv = _conversation(session, principal, conversation_id)
    session.execute(delete(AssistantMessage).where(AssistantMessage.conversation_id == conv.id))
    session.delete(conv)


def delete_all_conversations(session: Session, principal: Principal) -> int:
    ids = list(
        session.scalars(
            select(AssistantConversation.id).where(
                AssistantConversation.user_id == principal.user_id
            )
        )
    )
    if ids:
        session.execute(delete(AssistantMessage).where(AssistantMessage.conversation_id.in_(ids)))
        session.execute(delete(AssistantConversation).where(AssistantConversation.id.in_(ids)))
    return len(ids)


