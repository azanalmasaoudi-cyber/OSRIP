def _check_limits(session: Session, principal: Principal) -> None:
    s = get_settings()
    current = accounts.now()
    for window, limit in (
        (timedelta(minutes=1), s.assistant_max_per_minute),
        (timedelta(hours=1), s.assistant_max_per_hour),
        (timedelta(days=1), s.assistant_max_per_day),  # signed-in fair use
    ):
        used = (
            session.scalar(
                select(func.count()).where(
                    AssistantUsage.user_id == principal.user_id,
                    AssistantUsage.created_at >= current - window,
                )
            )
            or 0
        )
        if used >= limit:
            raise ApiError(
                429,
                "assistant_rate_limited",
                "You have reached the assistant's request limit. Wait a little and try again.",
            )


