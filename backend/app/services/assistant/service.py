def _history(session: Session, conv: AssistantConversation) -> list[dict[str, Any]]:
    rows = list(
        session.scalars(
            select(AssistantMessage)
            .where(AssistantMessage.conversation_id == conv.id)
            .order_by(AssistantMessage.id.desc())
            .limit(HISTORY_MESSAGES)
        )
    )[::-1]
    out: list[dict[str, Any]] = []
    for m in rows:
        if m.role == "assistant" and m.status not in (
            "answered",
            "clarification",
            "no_evidence",
            "profile",
        ):
            continue
        out.append({"role": m.role, "content": m.content})
    return _turns(out)


_OLD_EVIDENCE_ID = re.compile(r" ?\[E\d+\]")


def previous_tables(session: Session, conv: AssistantConversation) -> list[dict[str, Any]]:
    """The parameters of tables built in the conversation's recent answers, oldest first, so a
    follow-up such as "Draw it" can draw the same verified rows."""
    rows = session.scalars(
        select(AssistantMessage.structured)
        .where(
            AssistantMessage.conversation_id == conv.id,
            AssistantMessage.role == "assistant",
        )
        .order_by(AssistantMessage.id.desc())
        .limit(HISTORY_MESSAGES)
    ).all()
    out = []
    for structured in reversed(rows):
        for t in (structured or {}).get("data_tables") or []:
            if isinstance(t, dict) and isinstance(t.get("params"), dict):
                out.append(t["params"])
    return out[-3:]


def _turns(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Alternating turns starting with the user, as the APIs require. A question whose reply
    was not kept is followed by UNANSWERED instead of being joined to the next question.
    Earlier replies lose their evidence ids: each question has its own evidence, numbered from
    E1, so an old "[E85]" names another record now (a figure repeated with it was withheld)."""
    out = [
        {**m, "content": _OLD_EVIDENCE_ID.sub("", m["content"])} if m["role"] == "assistant" else m
        for m in messages
    ]
    while out and out[0]["role"] != "user":
        out.pop(0)
    merged: list[dict[str, Any]] = []
    for m in out:
        if merged and merged[-1]["role"] == m["role"] == "user":
            merged += [{"role": "assistant", "content": UNANSWERED}, dict(m)]
        elif merged and merged[-1]["role"] == m["role"]:
            merged[-1]["content"] += "\n" + m["content"]
        else:
            merged.append(dict(m))
    return merged


def _run_model(
    question: str,
    history: list[dict[str, Any]],
    language: str,
    data_mode: DataMode,
    web: bool = False,
    client_key: str | None = None,
    mode: str = "ask",
    tracker: Tracker | None = None,
    persona: str | None = None,
    cross_check: bool = False,
    selection: dict[str, Any] | None = None,
    submitter: Any = None,
    previous_tables: list[dict[str, Any]] | None = None,
    job_id: uuid.UUID | None = None,
) -> tuple[dict[str, Any], Ledger, str]:
    tracker = tracker or Tracker(None)
    s = get_settings()
    provider = get_provider()
    fallback = get_fallback_provider()
    switched: dict[str, Any] | None = None
    if provider is None and fallback is not None:
        # The primary is not configured: the fallback answers, and the reply says so.
        switched = {
            "from": s.assistant_provider or None,
            "to": fallback.vendor,
            "reason": "not_configured",
        }
        provider, fallback = fallback, None
    if provider is None:
        raise ProviderError("not_configured")
    wanted_web = web
    web = web and research.available()
    route = routing.classify(question)
    ledger = Ledger(
        data_mode,
        language=language,
        web_enabled=web,
        client_key=client_key,
        web_first=route.web_first,
        cross_check=cross_check and mode == "research",
    )
    ledger.meta = {
        "answer_provider": provider.vendor,
        "answer_model": provider.name,
        "fallback": switched,
        "route": route.as_dict(),
    }
    ledger.question = question
    ledger.submitter = submitter if web else None
    ledger.previous_tables = list(previous_tables or [])
    ledger.job_id = job_id
    if mode == "research":
        ledger.max_searches = s.research_max_searches_research
        ledger.max_pages = s.research_max_pages_research
    if tracker.stream is not None:
        ledger.on_add = tracker.stream.on_evidence  # sources appear as they are retrieved
    if wanted_web and not web and mode == "research":
        # Research mode was chosen but no search provider is configured: recorded, so the
        # reply shows that no search was made instead of implying one.
        ledger.add(
            {
                "kind": "search",
                "status": "not_configured",
                "query": question[:300],
                "provider": None,
            }
        )
    specs = tool_specs(
        web,
        mode,
        can_submit=ledger.submitter is not None,
        chart=routing.asks_for_chart(question),
    )
    rounds = s.research_max_rounds if mode == "research" else MAX_ROUNDS
    if history and history[-1]["role"] == "user":
        history = [*history, {"role": "assistant", "content": UNANSWERED}]  # see _turns
    messages: list[dict[str, Any]] = [
        *history,
        {"role": "user", "content": [{"type": "text", "text": question}]},
    ]
    current = profile.active_now()
    who = None
    if current is not None:
        codes = {x.code for x in profile.personas(current.profile)}
        who = profile.persona(current.profile, persona if persona in codes else None)
    system = SYSTEM_PROMPT.format(
        identity=profile.prompt_block(current.profile, current.version, who)
        if current
        else "You are the OSRIP resource analysis assistant.",
        language="Arabic" if language == "ar" else "English",
        data_mode=data_mode.value,
        cutoff=research_cutoff() or "the dates shown with each record",
        web_rules=WEB_RULES if web else NO_WEB_RULES,
        mode_rules=MODE_RULES.get(mode, MODE_RULES["ask"]),
        selection_rule=selection_rule(selection) + tables_rule(ledger.previous_tables, question),
    )
    seconds = get_settings().assistant_timeout_seconds * 2
    if mode == "research":
        seconds = max(seconds, s.research_answer_seconds)
    deadline = time.monotonic() + seconds
    with session_factory()() as reader:
        reader.begin()
        reader.execute(text("SET TRANSACTION READ ONLY"))  # the assistant cannot write
        tools = Tools(reader, ledger)
        try:
            for round_ in range(rounds):
                if time.monotonic() > deadline:
                    raise ProviderError("deadline")
                tracker.check()  # stopped by the person: no further model call
                # The last round can only answer: the model gives its answer from the evidence
                # gathered so far (checked as every answer is) instead of running out of rounds
                # while it looks the same figures up again.
                offered = (
                    specs
                    if round_ < rounds - 1
                    else [t for t in specs if t["name"] == "final_answer"]
                )
                try:
                    reply = provider.complete(system, messages, offered)
                except ProviderError as exc:
                    # One provider per question: the fallback takes over only when the primary
                    # fails before its first answer, never alongside it or mid-way.
                    code = str(exc)
                    if (
                        round_ > 0
                        or fallback is None
                        or not (
                            transient(code)
                            or code in ("daily_limit", "budget_exhausted", "http_402")
                        )
                    ):
                        raise
                    switched = {"from": provider.vendor, "to": fallback.vendor, "reason": code}
                    provider, fallback = fallback, None
                    ledger.meta.update(
                        answer_provider=provider.vendor,
                        answer_model=provider.name,
                        fallback=switched,
                    )
                    reply = provider.complete(system, messages, offered)
                blocks = [b for b in reply.get("content", []) if isinstance(b, dict)]
                calls = [b for b in blocks if b.get("type") == "tool_use"]
                final = next(
                    (
                        c
                        for c in calls
                        if c.get("name") == "final_answer" and not c.get("invalid_arguments")
                    ),
                    None,
                )
                if final is not None:
                    return final.get("input") or {}, ledger, provider.name
                if not calls:
                    raise ProviderError("no_tool_call")
                messages.append({"role": "assistant", "content": blocks})
                results = []
                for c in calls:
                    name = str(c.get("name"))
                    tracker.check()
                    if c.get("invalid_arguments"):  # flagged by the adapter: the model may retry
                        output: dict[str, Any] = {
                            "error": "invalid_arguments",
                            "message": INVALID_ARGUMENTS,
                        }
                    else:
                        tracker.tool(name)  # a stage is shown only for a step really taken
                        output = run_tool(tools, name, dict(c.get("input") or {}))
                        if tracker.stream is not None:
                            # Validated tables from OSRIP's own tools, or a partial failure.
                            tracker.stream.on_tool(name, output, ledger.by_id(), tracker)
                    results.append(
                        {
                            "type": "tool_result",
                            "tool_use_id": c.get("id"),
                            "content": json.dumps(output, ensure_ascii=False, default=str),
                        }
                    )
                if round_ == rounds - 2:
                    results.append({"type": "text", "text": LAST_ROUND})
                messages.append({"role": "user", "content": results})
            raise ProviderError("too_many_rounds")
        except ProviderError as exc:
            # Who failed, and the evidence gathered so far (the data report continues it).
            exc.provider = exc.provider or provider.vendor
            exc.model = exc.model or provider.name
            exc.ledger = ledger
            raise
        finally:
            reader.rollback()


def research_cutoff() -> str | None:
    """Research cutoff of the latest loaded reference pack (e.g. '2026-09-27')."""
    with session_factory()() as s, s.begin():
        cutoff = s.scalar(select(func.max(ReferencePack.research_cutoff)))
    return cutoff.isoformat() if cutoff else None


@dataclass
class Reply:
    """One assistant reply before it is stored. ``outcome`` is recorded in usage rows."""

    content: str
    status: str
    outcome: str
    evidence: list[dict[str, Any]] = field(default_factory=list)
    calculations: list[dict[str, Any]] = field(default_factory=list)
    citations: list[str] = field(default_factory=list)
    suggestions: list[str] = field(default_factory=list)
    model: str | None = None
    # Proposed web observations and the full ledger they are checked against.
    web_records: list[dict[str, Any]] = field(default_factory=list)
    ledger_items: list[dict[str, Any]] = field(default_factory=list)
    # The reply only reports that the web search could not be made (an outage, a limit):
    # a failed request, so it is never charged to a guest's allowance.
    search_failed: bool = False
    mode: str = "ask"
    # Validated recommendation cards, drivers, evidence/hypotheses/assumptions, conflicts.
    structured: dict[str, Any] = field(default_factory=dict)
    # Cited deterministic studies (id, full validated result), stored with the message.
    studies: list[tuple[str, dict[str, Any]]] = field(default_factory=list)
    # The persona that gives this reply (stored with the message).
    persona: str | None = None
    # Figures submitted for validation in this answer (research_candidate ids).
    research_ids: list[str] = field(default_factory=list)

    def store_studies(
        self,
        session: Session,
        message_id: int,
        *,
        user_id: uuid.UUID | None = None,
        guest_session_id: uuid.UUID | None = None,
    ) -> None:
        from app.services import studies

        for study_id, document in self.studies:
            studies.store(
                session,
                document,
                study_id=uuid.UUID(study_id),
                user_id=user_id,
                guest_session_id=guest_session_id,
                message_id=message_id,
            )

    def queue_research(
        self, session: Session, message_id: int, proposed_by: uuid.UUID | None, language: str
    ) -> int:
        """Link the figures submitted in this answer to its message, and send the reply's other
        numerical web findings to the review queue (never the dataset)."""
        if self.research_ids:
            session.execute(
                update(ResearchCandidate)
                .where(
                    ResearchCandidate.id.in_([uuid.UUID(i) for i in self.research_ids]),
                    ResearchCandidate.message_id.is_(None),
                )
                .values(message_id=message_id)
            )
        if not self.web_records or self.status not in ("answered", "no_evidence"):
            return 0
        return research.queue_candidates(
            session,
            self.web_records,
            self.ledger_items,
            citations=self.citations,
            message_id=message_id,
            proposed_by=proposed_by,
            language=language,
        )

    @property
    def chargeable(self) -> bool:
        """A completed reply accepted by the response contract (booklet 3.35). Withheld,
        failed and non-AI lookup replies never consume an answer."""
        return self.status in CHARGEABLE and not self.search_failed

    def message(self, conversation_id: uuid.UUID) -> AssistantMessage:
        return AssistantMessage(
            conversation_id=conversation_id,
            role="assistant",
            content=self.content,
            status=self.status,
            evidence=self.evidence,
            calculations=self.calculations,
            citations=self.citations,
            suggestions=self.suggestions,
            model=self.model,
            mode=self.mode,
            structured=self.structured,
            persona=self.persona,
        )


def normalise_mode(mode: str | None) -> str:
    return mode if mode in MODES else "ask"


def validate_question(content: str, language: str) -> tuple[str, str]:
    s = get_settings()
    question = content.strip()
    if not question:
        raise unprocessable("empty_message", "Type a question first.")
    if len(question) > s.assistant_max_message_chars:
        raise unprocessable(
            "message_too_long", f"Keep questions under {s.assistant_max_message_chars} characters."
        )
    return question, "ar" if language == "ar" else "en"


def question_digest(question: str, language: str) -> str:
    return hashlib.sha256(f"{language}\n{' '.join(question.split())}".encode()).hexdigest()


def method_summary(
    items: list[dict[str, Any]], stages: list[str], meta: dict[str, Any] | None = None
) -> dict[str, Any]:
    """What was actually done for this answer, counted from the evidence ledger: the steps
    taken, published records and calculations used, searches (and their languages), pages
    read, sources that may be out of date, which providers were used (and why a fallback or
    a cross-check was), and the routing decision. Shown as "How this answer was prepared"."""
    kinds = Counter(str(i.get("kind")) for i in items)
    searches = [i for i in items if i.get("kind") == "search"]
    web = [i for i in items if i.get("kind") == "web"]
    meta = meta or {}
    routes = [
        {"provider": s.get("provider"), "role": s.get("role", "primary"), "status": s.get("status"),
         "display_only": bool(s.get("display_only"))}
        for s in searches
        if s.get("provider")
    ]  # fmt: skip
    return {
        "answer_provider": meta.get("answer_provider"),
        "answer_model": meta.get("answer_model"),
        "answer_fallback": meta.get("fallback"),
        "route": meta.get("route"),
        "search_routes": routes,
        "provider_summaries": sum(1 for w in web if w.get("content_kind") == "provider_summary"),
        "grounded_results": kinds["grounded_context"],
        "steps": [s for s in stages if s != "received"],
        "published_records": kinds["observation"],
        "calculations": kinds["calculation"] + kinds["method"],
        "studies": kinds["study"],
        "searches": sum(1 for s in searches if s.get("status") in ("ok", "no_results")),
        "failed_searches": sum(1 for s in searches if s.get("status") not in ("ok", "no_results")),
        "search_languages": sorted({str(x) for s in searches for x in s.get("languages") or []}),
        "web_results": sum(1 for w in web if w.get("content_kind") == "search_snippet"),
        "pages_read": sum(
            1 for w in web if w.get("content_kind") in ("page_excerpt", "pdf_excerpt")
        ),
        "stale_sources": sum(1 for w in web if w.get("freshness") == "stale"),
        "undated_sources": sum(1 for w in web if w.get("freshness") == "undated"),
    }


def _with_topic(question: str, history: list[dict[str, Any]]) -> str:
    """For the replies made without the model (the data-based report, the plain lookup): a
    follow-up that names no topic but asks for a figure, change or comparison ("Compare it with
    the previous year") is read together with the latest earlier question that names one, as the
    model would read it from the conversation. Small talk ("How is it going?") is left alone."""
    if lookup.matched_domains(question) or not routing.classify(question).numerical:
        return question
    for turn in reversed(history):
        text = turn.get("content")
        if turn.get("role") == "user" and isinstance(text, str) and lookup.matched_domains(text):
            return f"{text}\n{question}"
    return question


def generate_reply(
    question: str,
    history: list[dict[str, Any]],
    language: str,
    data_mode: DataMode,
    *,
    web: bool = False,
    client_key: str | None = None,
    mode: str = "ask",
    tracker: Tracker | None = None,
    persona: str | None = None,
    cross_check: bool = False,
    selection: dict[str, Any] | None = None,
    submitter: Any = None,
    previous_tables: list[dict[str, Any]] | None = None,
    job_id: uuid.UUID | None = None,
) -> Reply:
    """The grounded answer, the labelled non-AI lookup when no provider is configured,
    a retryable 'unavailable' reply, or 'cancelled' when the person stopped the question.
    Runs outside any caller transaction.

    Research mode searches the web whenever a search provider is configured; the other
    modes only when the user switched web research on. ``persona`` only names who replies:
    the tools, evidence checks and validation are identical for every persona.
    ``cross_check`` (Research mode, asked for by the person): a second search route too."""
    mode = normalise_mode(mode)
    tracker = tracker or Tracker(None)
    if get_provider() is None and get_fallback_provider() is None:
        found = lookup.reply(_with_topic(question, history), language, data_mode)
        return Reply(
            content=found["content"],
            status="lookup",
            outcome="lookup",
            evidence=found["evidence"],
            citations=found["citations"],
            mode=mode,
            persona=persona,
        )
    try:
        final, ledger, model = _run_model(
            question,
            history,
            language,
            data_mode,
            web=web or mode == "research",
            client_key=client_key,
            mode=mode,
            tracker=tracker,
            persona=persona,
            cross_check=cross_check,
            selection=selection,
            submitter=submitter,
            previous_tables=previous_tables,
            job_id=job_id,
        )
    except Cancelled:
        return Reply(
            content=MESSAGES["cancelled"][language],
            status="cancelled",
            outcome="cancelled",
            mode=mode,
            persona=persona,
        )
    except ProviderError as exc:
        return degraded_reply(
            exc, _with_topic(question, history), language, data_mode, mode, tracker, persona
        )
    tracker.stage("checking")
    status_ = str(final.get("status", ""))
    reply_text = str(final.get("text", "")).strip()
    # Inline markers count as citations too, so a source cited in the text is always listed.
    citations = list(
        dict.fromkeys(
            [str(c) for c in final.get("citations") or []] + grounding.inline_markers(reply_text)
        )
    )[:20]
    suggestions = [str(q)[:200] for q in final.get("suggested_questions") or []][:3]
    # Google Search grounded results are display-only: never evidence for the answer.
    grounded = [i for i in ledger.items if i.get("kind") == "grounded_context"]
    visible = [i for i in ledger.items if i.get("kind") != "grounded_context"]
    verdict = grounding.validate(reply_text, citations, visible)
    structured: dict[str, Any] = {}
    if status_ not in CHARGEABLE or not reply_text or not verdict.ok:
        # For the operator: why it was withheld (the check's findings, never the answer text).
        log.warning(
            "assistant answer withheld provider=%s model=%s status=%s problems=%s",
            ledger.meta.get("answer_provider"),
            model,
            status_ or "-",
            "; ".join(verdict.problems) or ("empty text" if not reply_text else "-"),
        )
        status_, reply_text, citations = "unverified", MESSAGES["unverified"][language], []
    else:
        structured = grounding.validate_structured(final, visible, question=question, mode=mode)
        # Sources cited only by a card, a driver or a conflict are shown with the reply too.
        for part in structured.values():
            for entry in part if isinstance(part, list) else []:
                ids = list(entry.get("citations", [])) + [
                    v["evidence_id"] for v in entry.get("values", [])
                ]
                citations.extend(i for i in ids if i not in citations)
    cited = set(citations)
    evidence = (
        list(visible) if status_ == "unverified" else [i for i in visible if i["id"] in cited]
    )
    # Inputs of cited calculations and scenarios are shown too, for "How calculated".
    by_id = ledger.by_id()
    for item in list(evidence):
        for input_id in item.get("inputs", []):
            if input_id in by_id and by_id[input_id] not in evidence:
                evidence.append(by_id[input_id])
    # Every web search attempt is shown, successful or not, so a reply can never imply a
    # search that failed or did not happen.
    for item in ledger.items:
        if item.get("kind") == "search" and item not in evidence:
            evidence.append(item)
    # Cited studies are stored with the reply (outside this read-only step); the message keeps
    # a short reference and the evidence list a slim item without the full table.
    cited_studies = (
        [i for i in evidence if i.get("kind") == "study"] if status_ != "unverified" else []
    )
    if cited_studies:
        structured["studies"] = [
            {
                "id": i["study_id"],
                "kind": i["study_kind"],
                "title": i["title"],
                "status": i["status"],
            }
            for i in cited_studies
        ]
    evidence = [
        {k: v for k, v in i.items() if k != "study"} if i.get("kind") == "study" else i
        for i in evidence
    ]
    structured["method"] = method_summary(ledger.items, tracker.reached, ledger.meta)
    if grounded:
        # Shown verbatim with Google's search suggestions, apart from the answer.
        structured["grounded_context"] = [
            {k: g.get(k) for k in (
                "provider", "attribution", "model", "text", "citations", "search_suggestions",
                "queries", "retrieved_at", "stored_at", "role",
            )}
            for g in grounded
        ]  # fmt: skip
    notice = web_failure_notice(ledger.items)
    if notice is not None:
        structured["web_notice"] = notice
    # Built by the backend from published data, valid whatever happens to the text.
    if ledger.tables:
        structured["data_tables"] = ledger.tables
    if ledger.charts and routing.asks_for_chart(question):
        structured["data_charts"] = ledger.charts
    summary = research_summary(ledger)
    if summary is not None:
        structured["research"] = summary
    records = final.get("web_records") if isinstance(final.get("web_records"), list) else []
    searches = [i for i in ledger.items if i.get("kind") == "search"]
    search_failed = (
        status_ == "no_evidence"
        and bool(searches)
        and all(i.get("status") in ("failed", "rate_limited", "not_configured") for i in searches)
    )
    return Reply(
        search_failed=search_failed,
        content=reply_text,
        status=status_,
        outcome=status_,
        evidence=[i for i in evidence if i.get("kind") not in ("calculation", "method")],
        calculations=[i for i in evidence if i.get("kind") in ("calculation", "method")],
        citations=citations,
        suggestions=suggestions,
        model=model,
        web_records=[r for r in records if isinstance(r, dict)],
        ledger_items=ledger.items,
        mode=mode,
        structured=structured,
        studies=[(i["study_id"], i["study"]) for i in cited_studies],
        persona=persona,
        research_ids=[r["candidate_id"] for r in ledger.submissions if r.get("candidate_id")],
    )


def research_summary(ledger: Ledger) -> dict[str, Any] | None:
    """What this answer's research did, from the records themselves: the documents read, and
    for submitted figures what was saved (only after the database transaction committed),
    skipped as duplicate, kept as a conflict or pending, or refused."""
    read = [
        i
        for i in ledger.items
        if i.get("kind") == "web" and i.get("content_kind") in ("page_excerpt", "pdf_excerpt")
    ]
    if not read and not ledger.submissions:
        return None
    sources_read = []
    seen: set[str] = set()
    for i in read:
        if i["url"] in seen:
            continue
        seen.add(i["url"])
        sources_read.append(
            {
                "evidence_id": i["id"],
                "title": i.get("title"),
                "url": i["url"],
                "publisher": (i.get("publisher") or {}).get("en"),
                "source_class": i.get("source_class"),
                "published": i.get("published"),
                "retrieved_at": i.get("retrieved_at"),
                "read_by": i.get("retriever"),
                "cached": bool(i.get("cached")),
            }
        )
    counts: dict[str, int] = {}
    for r in ledger.submissions:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    saved = [r for r in ledger.submissions if r.get("saved")]
    latest = max((r.get("period") or "" for r in saved), default=None) if saved else None
    return {
        "searched_at": next(
            (i.get("retrieved_at") for i in ledger.items if i.get("kind") == "search"), None
        ),
        "sources_read": sources_read,
        "submitted": len(ledger.submissions),
        "counts": counts,
        "saved": saved,
        "not_saved": [r for r in ledger.submissions if not r.get("saved")],
        "latest_saved_period": latest,
    }


def degraded_reply(
    exc: ProviderError,
    question: str,
    language: str,
    data_mode: DataMode,
    mode: str,
    tracker: Tracker,
    persona: str | None,
) -> Reply:
    """The answer service failed. What failed is logged with the request id (codes and the
    service's error type only: never a key, a header or a message text), and the question
    gets the data-based report without AI interpretation (``data_report``), which is not
    charged and can be retried. Only if that report cannot be built is the reply the plain
    'unavailable' message."""
    code = str(exc)
    category = failure_category(code, exc.detail)
    incident = tracker.stream.study_id if tracker.stream is not None else uuid.uuid4().hex
    log.warning(
        "assistant provider failed request_id=%s provider=%s model=%s code=%s detail=%s "
        "category=%s",
        incident,
        exc.provider or get_settings().assistant_provider,
        exc.model,
        code,
        exc.detail,
        category,
    )
    try:
        report = data_report.build(
            question, language, data_mode, category=category, incident=incident,
            ledger=exc.ledger, tracker=tracker,
        )  # fmt: skip
    except Cancelled:
        return Reply(
            content=MESSAGES["cancelled"][language],
            status="cancelled",
            outcome="cancelled",
            mode=mode,
            persona=persona,
        )
    except Exception:  # noqa: BLE001 - the person still gets a clear, retryable reply
        log.exception("data report failed request_id=%s", incident)
        return Reply(
            content=MESSAGES["unavailable"][language],
            status="unavailable",
            outcome="unavailable",
            mode=mode,
            persona=persona,
            structured={"incident": incident, "failure": category},
        )
    tracker.stage("checking")
    studies = report["studies"]
    structured: dict[str, Any] = {"data_report": report["notice"]}
    if studies:
        structured["studies"] = [
            {"id": i["study_id"], "kind": i["study_kind"], "title": i["title"],
             "status": i["status"]}
            for i in studies
        ]  # fmt: skip
    structured["method"] = method_summary(report["ledger"].items, tracker.reached, {})
    evidence = [
        {k: v for k, v in i.items() if k != "study"} if i.get("kind") == "study" else i
        for i in report["evidence"]
    ]
    return Reply(
        content=report["content"],
        status="data_report",
        outcome="data_report",
        evidence=[i for i in evidence if i.get("kind") not in ("calculation", "method")],
        calculations=[i for i in evidence if i.get("kind") in ("calculation", "method")],
        citations=report["citations"],
        mode=mode,
        structured=structured,
        studies=[(i["study_id"], i["study"]) for i in studies],
        persona=persona,
    )


def web_failure_notice(items: list[dict[str, Any]]) -> dict[str, Any] | None:
    """When every web search of an answer failed, the answer rests on OSRIP's verified data
    only: say so, with when that data was last updated."""
    searches = [i for i in items if i.get("kind") == "search"]
    failed = [
        i for i in searches if i.get("status") in ("failed", "rate_limited", "not_configured")
    ]
    if not searches or len(failed) < len(searches):
        return None
    published = [
        str(i["published_at"])
        for i in items
        if i.get("kind") == "observation" and i.get("published_at")
    ]
    return {
        "web_search": "not_configured" if all(i.get("status") == "not_configured" for i in failed) else "failed",
        "data_last_updated": data_report._latest(published),
        "research_cutoff": research_cutoff(),
    }  # fmt: skip


def ask(
    session: Session,
    principal: Principal,
    conversation_id: uuid.UUID,
    content: str,
    language: str,
    request_id: uuid.UUID | None = None,
    *,
    web: bool = False,
    client_key: str | None = None,
    mode: str = "ask",
    persona: str | None = None,
    cross_check: bool = False,
    selection: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """A signed-in user's question. With ``request_id`` a repeated submission (for
    example after a dropped connection) returns the stored reply instead of asking again.
    ``persona``: who replies (default: the person's saved choice, then the profile's).
    ``cross_check``: in Research mode, also search with the second route (asked for)."""
    question, language = validate_question(content, language)
    digest = question_digest(question, language)

    with session.begin():
        conv = _conversation(session, principal, conversation_id)
        persona = resolve_persona(session, persona, user_id=principal.user_id)
        request: AssistantRequest | None = None
        if request_id is not None:
            request = session.scalar(
                select(AssistantRequest)
                .where(
                    AssistantRequest.user_id == principal.user_id,
                    AssistantRequest.idempotency_key == request_id,
                )
                .with_for_update()
            )
            if request is not None:
                if request.question_digest != digest:
                    raise idempotency_conflict()
                if request.state == "completed" and request.response_message_id is not None:
                    stored = session.get(AssistantMessage, request.response_message_id)
                    if stored is not None:
                        return {**_message_out(stored), "replayed": True}
                if request.state == "reserved" and request.reserved_until > accounts.now():
                    raise request_in_progress()
        approved = profile_turn(session, conv, question, language, persona)
        if approved is not None:
            # A greeting or identity question: the approved reply, no model call and no
            # usage counted against fair-use limits.
            if request is None:  # a retried question is already in the thread
                session.add(
                    AssistantMessage(conversation_id=conv.id, role="user", content=question)
                )
            message = approved.message(conv.id)
            session.add(message)
            conv.updated_at = accounts.now()
            session.flush()
            if request_id is not None:
                if request is None:
                    request = AssistantRequest(
                        user_id=principal.user_id,
                        idempotency_key=request_id,
                        question_digest=digest,
                        language=language,
                        state="completed",
                        conversation_id=conv.id,
                        reserved_until=accounts.now(),
                    )
                    session.add(request)
                request.state, request.charged, request.outcome = "completed", False, "profile"
                request.response_message_id, request.completed_at = message.id, accounts.now()
            return _message_out(message)
        _check_limits(session, principal)
        history = _history(session, conv)
        tables = previous_tables(session, conv)
        data_mode = conv.data_mode
        retry = request is not None
        if retry and history and history[-1]["role"] == "user":
            history = history[:-1]  # the question itself is sent once, below
        if request_id is not None:
            until = accounts.now() + reservation_window()
            if request is None:
                request = AssistantRequest(
                    user_id=principal.user_id,
                    idempotency_key=request_id,
                    question_digest=digest,
                    language=language,
                    state="reserved",
                    conversation_id=conv.id,
                    reserved_until=until,
                )
                session.add(request)
            else:
                request.state, request.reserved_until = "reserved", until
                request.attempts += 1
            start_progress(request)
            session.flush()
        if not retry:  # a retry of the same failed question does not repeat it in the thread
            session.add(AssistantMessage(conversation_id=conv.id, role="user", content=question))
        if conv.title in ("New conversation", "محادثة جديدة"):
            conv.title = question[:80]
        conv.updated_at = accounts.now()
        request_pk = request.id if request is not None else None
        attempt = request.attempts if request is not None else 1

    tracker = study_tracker(
        request_pk, request_id, conversation_id, language, data_mode, mode, attempt
    )
    reply = generate_reply(
        question,
        history,
        language,
        data_mode,
        web=web,
        client_key=client_key,
        mode=mode,
        tracker=tracker,
        persona=persona,
        cross_check=cross_check,
        # Only a person allowed to submit figures gets the tool; validation decides the rest.
        submitter=principal if principal.has(Permission.RESEARCH_SUBMIT) else None,
        previous_tables=tables,
        selection=selection,
    )
    with_study(reply, tracker, request_id)

    with session.begin():
        message = reply.message(conversation_id)
        session.add(message)
        session.add(AssistantUsage(user_id=principal.user_id, outcome=reply.outcome))
        session.flush()
        reply.store_studies(session, message.id, user_id=principal.user_id)
        reply.queue_research(session, message.id, principal.user_id, language)
        if request_pk is not None:
            row = session.get(
                AssistantRequest, request_pk, with_for_update=True, populate_existing=True
            )
            if row is not None:
                settle(row, reply, message.id, charged=reply.chargeable)
        out = _message_out(message)
    tracker.finish(reply, out["id"])  # after the reply is stored
    return out


def study_tracker(
    request_pk: int | None,
    request_id: uuid.UUID | None,
    conversation_id: uuid.UUID | None,
    language: str,
    data_mode: DataMode,
    mode: str,
    attempt: int,
) -> Tracker:
    """The request's progress tracker with its live study stream (``study_events``); without
    a stored request there is nothing to stream to."""
    if request_pk is None or request_id is None:
        return Tracker(request_pk)
    from app.services.assistant.study_events import StudyStream

    stream = StudyStream(
        request_pk, str(request_id), conversation_id=conversation_id, language=language,
        data_mode=data_mode,
    )  # fmt: skip
    tracker = Tracker(request_pk, stream=stream)
    tracker.start(attempt=attempt, mode=normalise_mode(mode))
    return tracker


def with_study(reply: Reply, tracker: Tracker, request_id: uuid.UUID | None) -> None:
    """A reply prepared as a live study names it, so the person can return to it."""
    if tracker.stream is not None and request_id is not None:
        reply.structured = {**(reply.structured or {}), "study_id": str(request_id)}


def settle(row: AssistantRequest, reply: Reply, message_id: int, *, charged: bool) -> None:
    """Close a request with its stored reply: completed (replayable), cancelled by the
    person, or released for a retry. Only a completed request can be charged."""
    done = reply.chargeable or reply.status == "lookup"
    row.state = "completed" if done else "cancelled" if reply.status == "cancelled" else "released"
    row.charged = charged and done
    row.outcome = reply.outcome
    row.response_message_id = message_id if done or reply.status == "cancelled" else None
    row.completed_at = accounts.now()
    finish_progress(row, reply)


def request_progress(
    session: Session, request_id: uuid.UUID, *, user_id: uuid.UUID | None = None,
    guest_session_id: uuid.UUID | None = None,
) -> dict[str, Any]:  # fmt: skip
    """The stages of the caller's own request (none of another person's)."""
    from app.services.assistant import progress

    row = _own_request(session, request_id, user_id=user_id, guest_session_id=guest_session_id)
    return progress.view(row)


def narration_segment(session: Session, message_id: int, segment_id: str) -> str:
    """The text of one narration segment of a reply's completed live study (the caller has
    checked that the reply is theirs). Only text generated from the validated findings."""
    from app.models import StudyEvent

    done = session.scalar(
        select(StudyEvent)
        .where(
            StudyEvent.type == "study.completed",
            StudyEvent.payload["message_id"].astext == str(message_id),
        )
        .order_by(StudyEvent.id.desc())
        .limit(1)
    )
    for s in (done.payload.get("narration") if done else None) or []:
        if s.get("narration_segment_id") == segment_id:
            return str(s.get("text") or "")
    raise not_found("narration segment")


def study_events(
    session: Session, request_id: uuid.UUID, *, user_id: uuid.UUID | None = None,
    guest_session_id: uuid.UUID | None = None,
) -> dict[str, Any]:  # fmt: skip
    """Every live-study event of the caller's own request, in order (to return to a study)."""
    from app.models import StudyEvent
    from app.services.assistant import study_events as events

    row = _own_request(session, request_id, user_id=user_id, guest_session_id=guest_session_id)
    rows = session.scalars(
        select(StudyEvent).where(StudyEvent.request_id == row.id).order_by(StudyEvent.seq)
    ).all()
    return {
        "study_id": str(request_id),
        "state": row.state,
        "events": [events.public(e) for e in rows],
    }


def cancel_request(
    session: Session, request_id: uuid.UUID, *, user_id: uuid.UUID | None = None,
    guest_session_id: uuid.UUID | None = None,
) -> dict[str, Any]:  # fmt: skip
    """Ask a running request to stop. It ends at its next step with a 'cancelled' reply
    that is not charged; a request that has already finished is left as it is."""
    from app.services.assistant import progress

    row = _own_request(
        session, request_id, user_id=user_id, guest_session_id=guest_session_id, lock=True
    )
    if row.state == "reserved" and row.cancel_requested_at is None:
        row.cancel_requested_at = accounts.now()
    return progress.view(row)


def _own_request(
    session: Session, request_id: uuid.UUID, *, user_id: uuid.UUID | None,
    guest_session_id: uuid.UUID | None, lock: bool = False,
) -> AssistantRequest:  # fmt: skip
    if (user_id is None) == (guest_session_id is None):
        raise not_found("request")
    owner = (
        AssistantRequest.user_id == user_id
        if user_id is not None
        else AssistantRequest.guest_session_id == guest_session_id
    )
    stmt = select(AssistantRequest).where(owner, AssistantRequest.idempotency_key == request_id)
    row = session.scalar(stmt.with_for_update() if lock else stmt)
    if row is None:
        raise not_found("request")
    return row


def reservation_window() -> timedelta:
    """How long a reservation may stay open: the model deadline, one provider retry and a
    margin. An older open reservation is treated as abandoned and released."""
    return timedelta(seconds=get_settings().assistant_timeout_seconds * 4 + 30)


def idempotency_conflict() -> ApiError:
    return ApiError(
        422,
        "request_id_reused",
        "This request identifier was already used for a different question.",
    )


def request_in_progress() -> ApiError:
    return ApiError(
        409, "request_in_progress", "This question is still being answered. Wait a moment."
    )
