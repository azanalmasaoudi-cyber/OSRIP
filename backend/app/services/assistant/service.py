def start_progress(request: AssistantRequest) -> None:
    """A new or retried request starts with one 'received' stage and no stop request."""
    request.progress = [
        {"stage": "received", "at": accounts.now().replace(microsecond=0).isoformat()}
    ]
    request.cancel_requested_at = None


def finish_progress(row: AssistantRequest, reply: Reply) -> None:
    """The last stage, written with the stored reply (the row is locked by the caller)."""
    stage = "cancelled" if reply.status == "cancelled" else "done"
    at = accounts.now().replace(microsecond=0).isoformat()
    row.progress = [*(row.progress or []), {"stage": stage, "at": at}]


