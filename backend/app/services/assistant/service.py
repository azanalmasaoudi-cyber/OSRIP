"""The evidence-grounded assistant: conversations, limits, the tool loop and validation.

Flow for one user message:
1. Authorization (``assistant.use``), per-user limits (per minute and per hour).
2. The model is given the question, the recent conversation and read-only tools. It
   may call tools (evidence is recorded with IDs) and must end with ``final_answer``.
3. Tool calls run in a READ ONLY database transaction: the assistant cannot change
   records, roles or permissions whatever the model asks for.
4. The reply is checked against the evidence (grounding.validate). A reply that fails
   is withheld (status ``unverified``) and the evidence is shown instead.
5. Failures and timeouts become an ``unavailable`` reply that can be retried.
Replies are stored with their evidence, calculations and citations, and labelled as
AI-generated by the interface. Deleting a conversation deletes its messages.
"""

