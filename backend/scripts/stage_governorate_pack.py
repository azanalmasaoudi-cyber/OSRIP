            "## Commercial records (Ministry of Commerce, Industry and Investment Promotion)",
            "",
            f"`moc-active-commercial-records-2025.xlsx`, downloaded on {ACCESSED.isoformat()} "
            "from the Oman open data portal (Open Data License). Active records on record at "
            f"the end of 2025: {records.total:,} in {len(records.matched)} of 63 wilayats matched "
