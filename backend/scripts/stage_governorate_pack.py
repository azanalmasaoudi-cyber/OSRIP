        "Sharqiyah, the 'other' areas, Al Batinah's combined fishing) stay groups and are never "
        "shared out among governorates or wilayats; the count of enterprises of all economic "
        "activities is business context and is not imported as trade; the only wilayat figures "
        "are the ministry's commercial records, which it publishes by wilayat; no statistic of "
        "the pack is given to a wilayat.",
