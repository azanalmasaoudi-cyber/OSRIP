def stage(staged, username: str) -> list[str]:  # noqa: ANN001
    from sqlalchemy import select

    from app.core.errors import ApiError
    from app.db.session import session_factory
    from app.domain.enums import DataMode
    from app.models import Source
    from app.services import accounts
    from app.services.imports import owner_workbooks, workflow
    from app.services.principal import Principal

    out = []
    session = session_factory()()
    with session.begin():
        user = accounts.find_by_username(session, username)
        if user is None:
            raise SystemExit(f"error: no account '{username}'.")
        actor = Principal(user_id=user.id, label="system:cli:stage-governorate-pack")
    for url, rows in staged.items():
        meta = {k: v for k, v in (source_for(url) or {}).items() if k != "slug"}
        with session.begin():
            source = session.scalar(
                select(Source).where(
                    Source.url == url, Source.dataset_title == meta["dataset_title"]
                )
            )
        if source is None:
            source = workflow.register_source(
                session,
                actor,
                data_mode=DataMode.VERIFIED_SOURCE,
                url=url,
                access_date=ACCESSED,
                **meta,
            )
        slug = (source_for(url) or {})["slug"]
        try:
            state = workflow.create_import(
                session,
                actor,
                source_id=source.id,
                version_label=VERSION_LABEL,
                filename=f"{slug}.csv",
                data=owner_workbooks.csv_text(rows).encode("utf-8"),
            )
        except ApiError as exc:
            if exc.code not in ("duplicate_file", "version_label_taken"):
                raise
            out.append(f"{slug}: already staged ({exc.code}); nothing changed")
            continue
        state = workflow.validate_import(session, actor, state.job.id)
        out.append(
            f"{slug}: import {state.job.id}, {state.version.status.value}, "
            f"rows {state.job.row_count} "
            f"(rejected {state.job.rejected_row_count}, warnings {state.job.warning_row_count})"
        )
    return out


def reject(username: str) -> list[str]:
    """Rollback: reject this batch's imports that are not published yet."""
    from sqlalchemy import text

    from app.db.session import session_factory
    from app.services import accounts
    from app.services.imports import workflow
    from app.services.principal import Principal

    session = session_factory()()
    with session.begin():
        user = accounts.find_by_username(session, username)
        if user is None:
            raise SystemExit(f"error: no account '{username}'.")
        actor = Principal(user_id=user.id, label="system:cli:stage-governorate-pack")
        jobs = session.execute(
            text(
                "SELECT j.id, j.original_filename FROM import_job j "
                "JOIN dataset_version dv ON dv.id = j.dataset_version_id "
                "WHERE dv.version_label = :label "
                "AND dv.status IN ('draft', 'validated', 'approved')"
            ),
            {"label": VERSION_LABEL},
        ).all()
    out = []
    for job_id, filename in jobs:
        workflow.reject_import(
            session, actor, job_id, "Rolled back: governorate evidence pack staging withdrawn."
        )
        out.append(f"{filename}: import {job_id} rejected")
    return out or ["nothing to reject"]


def map_pack(book, areas):  # noqa: ANN001, ANN201
    from app.services.imports import governorate_pack as gp
    from app.services.imports import owner_workbooks as ow

    mapped, checks = ow.Mapped(), gp.Checks()
    gp.annual_2025(sow.sheet_rows(book, "Governorates 2025", 3), mapped, checks)
    gp.fishery_2025(sow.sheet_rows(book, "Fishery 2025", 3), mapped, checks)
    gp.latest_2026(sow.sheet_rows(book, "Latest 2026", 3), mapped, checks)
    gp.wilayats_63(sow.sheet_rows(book, "Wilayats 63", 3), areas, checks)
    return mapped, checks


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("workbook", type=Path)
    parser.add_argument("--stage", action="store_true", help="create and validate the imports")
    parser.add_argument("--reject", action="store_true", help="reject this batch's pending imports")
    parser.add_argument("--as", dest="username", help="the account the imports are attributed to")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")  # Arabic names in the messages
    if (args.stage or args.reject) and not args.username:
        parser.error("--stage and --reject need --as USERNAME")
    workbook = args.workbook.resolve()  # before moving into backend/
    os.chdir(BACKEND)
    from devdb import admin_url

    os.environ.setdefault("OSRIP_DATABASE_URL", admin_url("osrip_dev"))
    if args.reject:
        for line in reject(args.username):
            print(line)
        return 0

    from sqlalchemy import text

    from app.db.session import session_factory
    from app.services.imports import wilayat_evidence as we
    from app.services.sync.xlsx import Workbook

    book = Workbook(workbook.read_bytes(), dates=True)
    with session_factory()() as session, session.begin():
        areas = [
            we.Area(*row)
            for row in session.execute(
                text(
                    "SELECT a.code, a.name_en, a.name_ar, a.level::text, p.code FROM area a "
                    "LEFT JOIN area p ON p.id = a.parent_id"
                )
            ).all()
        ]
        mapped, checks = map_pack(book, areas)
        records = None
        if RECORDS_FILE.exists():
            from app.services.imports import governorate_pack as gp

            moc = Workbook(RECORDS_FILE.read_bytes(), dates=True)
            records = gp.commercial_records(
                sow.sheet_rows(moc, moc.sheet_names[0], 1), areas, mapped
            )
        staged, duplicates = swe.classify(
            mapped, sow.published_values(session), swe.staged_values(session)
        )
    problems = [r for r in checks.reconciliation() if not r[4]]
    if records is not None and (records.problems or len(records.matched) != 63):
        for p in records.problems:
            print(f"error: commercial records: {p}")
        return 1
    if problems or checks.wilayat_problems or checks.wilayats_matched != 63:
        for what, total, published, tolerance, _, where in problems:
            print(
                f"error: {what}: the areas add up to {total}, {where} is {published} (±{tolerance})"
            )
        for p in checks.wilayat_problems:
            print(f"error: {p}")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    from app.services.imports import owner_workbooks as ow

    for url, rows in staged.items():
        (OUT / f"{source_for(url)['slug']}.csv").write_bytes(ow.csv_text(rows).encode("utf-8"))
    text_report = report(staged, duplicates, mapped.skipped, checks, records)
    if args.stage:
        lines = stage(staged, args.username)
        text_report += f"\n## Staged on {date.today().isoformat()} (as {args.username})\n\n"
        text_report += "Each import is validated and waits for approval in Data Management.\n\n"
        text_report += "\n".join(f"- {line}" for line in lines) + "\n"
        print("\n".join(lines))
    (OUT / "README.md").write_bytes(text_report.encode("utf-8"))
    print(f"rows to stage: {sum(len(r) for r in staged.values())}; duplicates: {len(duplicates)}; "
          f"not imported: {len(mapped.skipped)}; report: {OUT / 'README.md'}")  # fmt: skip
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
