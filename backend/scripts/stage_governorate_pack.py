"""Stage the owner's governorate evidence pack of November 2026 as reviewed imports (nothing is
published).

    backend\\.venv\\Scripts\\python.exe scripts\\stage_governorate_pack.py PACK.xlsx
    ... scripts\\stage_governorate_pack.py PACK.xlsx --stage --as USERNAME
    ... scripts\\stage_governorate_pack.py PACK.xlsx --reject --as USERNAME

Without ``--stage`` this is a dry run: the pack is mapped (app/services/imports/
governorate_pack.py), its sums are checked against the NCSI publications' own totals, its 63
wilayats against the registry, and its figures against those already published or already waiting
for review; the import files and a report are written to docs/data-imports/2026-11-governorates/.
The database is not changed. ``--stage`` registers each publication as a verified source, creates
one import per publication and validates it: each then waits for a data manager's approval and
publication in Data Management. ``--reject`` is the rollback: it rejects this batch's imports that
are not yet published.

A sum that does not match its publication's total, or a wilayat whose governorate differs from the
registry's, stops the script before anything is written.
"""

