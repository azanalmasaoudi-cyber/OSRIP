def stage(staged, items, username: str) -> list[str]:  # noqa: ANN001
    from sqlalchemy import select

    from app.core.errors import ApiError
    from app.db.session import session_factory
    from app.domain.enums import DataMode
    from app.models import Source
    from app.services import accounts
    from app.services import outlook as outlook_service
    from app.services.imports import owner_workbooks, workflow
    from app.services.principal import Principal

    out = []
    session = session_factory()()
    with session.begin():
        user = accounts.find_by_username(session, username)
        if user is None:
            raise SystemExit(f"error: no account '{username}'.")
        actor = Principal(user_id=user.id, label="system:cli:stage-electricity-water")
    for url, rows in staged.items():
        meta = {k: v for k, v in REGISTRATION[url].items() if k != "slug"}
        with session.begin():
            source = session.scalar(
                select(Source).where(
                    Source.url == url, Source.dataset_title == meta["dataset_title"]
                )
            )
        if source is None:
            source = workflow.register_source(
                session,
                actor,
                data_mode=DataMode.VERIFIED_SOURCE,
                url=url,
                access_date=ACCESSED,
                **meta,
            )
        slug = REGISTRATION[url]["slug"]
        try:
            state = workflow.create_import(session, actor, source_id=source.id, version_label=VERSION_LABEL,
                                           filename=f"{slug}.csv", data=owner_workbooks.csv_text(rows).encode("utf-8"))  # fmt: skip
        except ApiError as exc:
            if exc.code not in ("duplicate_file", "version_label_taken"):
                raise
            out.append(f"{slug}: already staged ({exc.code}); nothing changed")
            continue
        state = workflow.validate_import(session, actor, state.job.id)
        out.append(f"{slug}: import {state.job.id}, {state.version.status.value}, rows {state.job.row_count} "
                   f"(rejected {state.job.rejected_row_count}, warnings {state.job.warning_row_count})")  # fmt: skip
    with session.begin():
        counts = outlook_service.stage(session, actor, items, VERSION_LABEL)
    out.append(
        f"outlook: {counts['inserted']} staged as pending, {counts['already_staged']} already staged"
    )
    return out


def reject(username: str) -> list[str]:
    from sqlalchemy import text

    from app.db.session import session_factory
    from app.services import accounts
    from app.services import outlook as outlook_service
    from app.services.imports import workflow
    from app.services.principal import Principal

    session = session_factory()()
    with session.begin():
        user = accounts.find_by_username(session, username)
        if user is None:
            raise SystemExit(f"error: no account '{username}'.")
        actor = Principal(user_id=user.id, label="system:cli:stage-electricity-water")
        jobs = session.execute(text(
            "SELECT j.id, j.original_filename FROM import_job j JOIN dataset_version dv ON dv.id = j.dataset_version_id "
            "WHERE dv.version_label = :label AND dv.status IN ('draft', 'validated', 'approved')"), {"label": VERSION_LABEL}).all()  # fmt: skip
        pending = [r[0] for r in session.execute(text(
            "SELECT id FROM outlook_item WHERE batch_label = :label AND review_status = 'pending'"), {"label": VERSION_LABEL})]  # fmt: skip
    out = []
    for job_id, filename in jobs:
        workflow.reject_import(
            session, actor, job_id, "Rolled back: electricity and water pack staging withdrawn."
        )
        out.append(f"{filename}: import {job_id} rejected")
    for item_id in pending:
        with session.begin():
            outlook_service.review(
                session, actor, item_id, "rejected", "Rolled back: staging withdrawn."
            )
    out.append(f"outlook: {len(pending)} pending items rejected")
    return out


def map_pack(workbook: Path):  # noqa: ANN201
    from app.services.imports import electricity_water_pack as ew
    from app.services.imports import owner_workbooks as ow
    from app.services.sync.xlsx import Workbook

    book = Workbook(workbook.read_bytes(), dates=True)
    mapped = ow.Mapped()
    ew.annual(sow.sheet_rows(book, "Electricity_Annual", 4), "Electricity_Annual", mapped)
    ew.annual(sow.sheet_rows(book, "Water_Annual", 4), "Water_Annual", mapped)
    ew.governorates(sow.sheet_rows(book, "Governorates_2025", 4), mapped)
    ew.nama_operations(sow.sheet_rows(book, "Nama_Water_Operations", 4), mapped)
    items = ew.outlook_items(sow.sheet_rows(book, "Nama_2026_2032", 4), ACCESSED.isoformat())
    return mapped, items


def governorate_totals(mapped) -> dict[str, Decimal]:  # noqa: ANN001
    """The 11 governorates' 2025 values from the governorate tables (pp. 134, 137) added up."""
    rows = [
        r
        for rs in mapped.rows.values()
        for r in rs
        if r["period_start"] == "2025-01-01"
        and ("p. 134" in r["source_locator"] or "p. 137" in r["source_locator"])
    ]

    def pick(code: str) -> Decimal:
        return sum((Decimal(r["value"]) for r in rows if r["indicator_code"] == code), Decimal(0))

    return {
        "elec": pick("ELEC_DISTRIBUTION"),
        "water_dist": pick("WATER_DISTRIBUTION"),
        "water_prod": pick("WATER_PRODUCTION"),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("workbook", type=Path)
    parser.add_argument(
        "--stage",
        action="store_true",
        help="create and validate the imports; stage the outlook as pending",
    )
    parser.add_argument(
        "--reject",
        action="store_true",
        help="reject this batch's unpublished imports and pending outlook items",
    )
    parser.add_argument("--as", dest="username", help="the account the staging is attributed to")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    if (args.stage or args.reject) and not args.username:
        parser.error("--stage and --reject need --as USERNAME")
    workbook = args.workbook.resolve()
    os.chdir(BACKEND)
    from devdb import admin_url

    os.environ.setdefault("OSRIP_DATABASE_URL", admin_url("osrip_dev"))
    if args.reject:
        print("\n".join(reject(args.username)))
        return 0
    from app.db.session import session_factory
    from app.services.imports import electricity_water_pack as ew
    from app.services.imports import owner_workbooks as ow

    try:
        mapped, items = map_pack(workbook)
    except ew.Mismatch as exc:
        print(f"error: {exc}")
        return 1
    with session_factory()() as session, session.begin():
        staged, duplicates = swe.classify(
            mapped, sow.published_values(session), swe.staged_values(session)
        )
    OUT.mkdir(parents=True, exist_ok=True)
    for url, rows in staged.items():
        (OUT / f"{REGISTRATION[url]['slug']}.csv").write_bytes(ow.csv_text(rows).encode("utf-8"))
    (OUT / "outlook-items.json").write_bytes(
        (json.dumps(items, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    )
    text_report = report(staged, duplicates, items, governorate_totals(mapped))
    if args.stage:
        lines = stage(staged, items, args.username)
        text_report += (
            f"\n## Staged on {date.today().isoformat()} (as {args.username})\n\n"
            + "\n".join(f"- {line}" for line in lines)
            + "\n"
        )
        print("\n".join(lines))
    (OUT / "README.md").write_bytes(text_report.encode("utf-8"))
    print(
        f"rows to stage: {sum(len(r) for r in staged.values())}; duplicates: {len(duplicates)}; outlook items: {len(items)}; report: {OUT / 'README.md'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
