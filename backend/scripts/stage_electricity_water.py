"""Stage the owner's electricity and water pack of November 2026 (nothing is published).

    backend\\.venv\\Scripts\\python.exe backend\\scripts\\stage_electricity_water.py PACK.xlsx
    ... stage_electricity_water.py PACK.xlsx --stage --as USERNAME
    ... stage_electricity_water.py PACK.xlsx --reject --as USERNAME

Without ``--stage`` this is a dry run (preview). The pack is mapped
(app/services/imports/electricity_water_pack.py) and every figure is compared with the value read
from its source document; a mismatch stops it. The observations are compared with those already
published or waiting for review. The import files, the outlook items and a report are written to
docs/data-imports/2026-11-electricity-water/, and the database is not changed.

``--stage`` registers each publication as a verified source, creates and validates one import per
publication (each then waits for a data manager's approval in Data Management), and stages the
outlook items as pending review (each is shown only once approved: POST /outlook/{id}/review).
Staging is idempotent: a file already staged and an outlook item already staged are left as they
are. ``--reject`` rejects this batch's unpublished imports and pending outlook items.
"""

